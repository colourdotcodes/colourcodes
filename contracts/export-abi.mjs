#!/usr/bin/env node
// Regenerates the ABI files the server and the browser use, from the Foundry build output.
//   cd contracts && forge build && node export-abi.mjs
// Writes:
//   server/abi/ColourcodeMiner.json, server/abi/ColourcodePool.json, server/abi/ERC20.json   (plain ABI arrays)
//   public/js/abi.js   ->  window.COLOURCODE_ABI = { miner: [...], pool: [...], erc20: [...] }
// Fails if the compiled ABI drifts from the fixed interface in SPEC.md section 5.1.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

function load(name) {
  const file = join(here, 'out', `${name}.sol`, `${name}.json`);
  try {
    return JSON.parse(readFileSync(file, 'utf8')).abi;
  } catch (e) {
    console.error(`cannot read ${file} - run "forge build" in contracts/ first`);
    process.exit(1);
  }
}

const miner = load('ColourcodeMiner');
const pool = load('ColourcodePool');

// Minimal ERC-20 surface the site needs (holder check, display).
const erc20 = [
  { type: 'function', name: 'balanceOf', stateMutability: 'view',
    inputs: [{ name: 'account', type: 'address' }], outputs: [{ name: '', type: 'uint256' }] },
  { type: 'function', name: 'decimals', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'uint8' }] },
  { type: 'function', name: 'symbol', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'string' }] },
];

// ---- interface check against SPEC 5.1 -------------------------------------------------------------
const sig = (e) => {
  const ins = e.inputs.map((i) => i.type + (e.type === 'event' && i.indexed ? ' indexed' : '')).join(',');
  const outs = e.outputs ? `->(${e.outputs.map((o) => `${o.type} ${o.name}`.trim()).join(',')})` : '';
  return `${e.type} ${e.name}(${ins})${outs}`;
};
const required = {
  ColourcodeMiner: [
    'function start()->()',
    'function mint(uint256,address)->(uint256 reward)',
    'function state()->(bytes32 challenge,uint256 target,uint256 height,uint256 reward,uint256 lastBlockTime,' +
      'uint256 reserve,uint256 minHold,uint256 minSpacing,uint256 startTime,bool started)',
    'function token()->(address)',
    'function genesisMessage()->(string)',
    'event Started(uint256,uint256,uint256)',
    'event Mined(uint256 indexed,address indexed,address indexed,uint256,bytes32,uint256,uint256)',
  ],
  ColourcodePool: [
    'function postEpoch(uint256,bytes32,uint256)->()',
    'function claim(uint256,address,uint256,bytes32[])->()',
    'function claimed(uint256,address)->(bool)',
    'function unallocated()->(uint256)',
    'event EpochPosted(uint256 indexed,bytes32,uint256)',
    'event Claimed(uint256 indexed,address indexed,uint256)',
  ],
};
let ok = true;
for (const [name, abi] of [['ColourcodeMiner', miner], ['ColourcodePool', pool]]) {
  const have = new Set(abi.filter((e) => e.type === 'function' || e.type === 'event').map(sig));
  for (const want of required[name]) {
    if (!have.has(want)) {
      console.error(`${name}: missing or changed -> ${want}`);
      ok = false;
    }
  }
}
if (!ok) process.exit(1);

// ---- write -------------------------------------------------------------------------------------------
mkdirSync(join(root, 'server', 'abi'), { recursive: true });
mkdirSync(join(root, 'public', 'js'), { recursive: true });
const pretty = (x) => JSON.stringify(x, null, 2) + '\n';
writeFileSync(join(root, 'server', 'abi', 'ColourcodeMiner.json'), pretty(miner));
writeFileSync(join(root, 'server', 'abi', 'ColourcodePool.json'), pretty(pool));
writeFileSync(join(root, 'server', 'abi', 'ERC20.json'), pretty(erc20));
writeFileSync(
  join(root, 'public', 'js', 'abi.js'),
  '// Generated by contracts/export-abi.mjs from the Foundry build. Do not edit by hand.\n' +
    `window.COLOURCODE_ABI = ${JSON.stringify({ miner, pool, erc20 })};\n`,
);
console.log(`ABI exported: miner ${miner.length} entries, pool ${pool.length} entries, erc20 ${erc20.length} entries`);
